"""make_report.py - собирает report.pdf из results/."""
import csv
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import cm
from reportlab.lib import colors
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Image, Table, TableStyle, PageBreak

pdfmetrics.registerFont(TTFont("D", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"))
pdfmetrics.registerFont(TTFont("DB", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"))
pdfmetrics.registerFont(TTFont("DM", "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"))
B = ParagraphStyle("b", fontName="D", fontSize=10, leading=14, spaceAfter=5)
H1 = ParagraphStyle("h1", fontName="DB", fontSize=13, leading=17, spaceBefore=10, spaceAfter=6)
T = ParagraphStyle("t", fontName="DB", fontSize=15, leading=20, alignment=1, spaceAfter=4)
C = ParagraphStyle("c", fontName="D", fontSize=9, leading=12, alignment=1, textColor=colors.HexColor("#444444"), spaceAfter=8)
M = ParagraphStyle("m", fontName="DM", fontSize=8.5, leading=11, leftIndent=8, spaceAfter=5)
P = lambda t, s=B: Paragraph(t, s)

REPO = "https://github.com/ВАШ_ЛОГИН/apriori-lab"   # <- заменить на реальную ссылку

def read(p):
    with open(p, encoding="utf-8") as f:
        return list(csv.reader(f))

def table(rows, widths, font=9):
    rows = [[Paragraph(str(c), ParagraphStyle("c", fontName="D", fontSize=font, leading=font+2)) for c in r] for r in rows]
    t = Table(rows, colWidths=widths, repeatRows=1)
    t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), .4, colors.grey), ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e8eef7")),
                           ("VALIGN", (0, 0), (-1, -1), "MIDDLE")]))
    return t

summ = read("results/summary.csv")
s = [P("Лабораторная работа: поиск частых наборов объектов алгоритмом Apriori", T),
     P("Дисциплина «Основы интеллектуального анализа данных (Big Data)»", C)]

s += [P("1. Формулировка задания", H1),
      P("Разработать программу, которая выполняет поиск частых наборов объектов в заданном наборе данных алгоритмом Apriori "
        "(или одной из его модификаций). Результат работы — частые наборы и значение поддержки для каждого. "
        "Параметры программы: набор данных, порог поддержки, способ упорядочивания результата "
        "(по убыванию поддержки или лексикографически)."),
      P("Провести эксперименты на наборе данных baskets.csv (покупки в супермаркете) с порогами поддержки 1%, 3%, 5%, 10%, 15%. "
        "Построить две диаграммы: (а) время работы при фиксированном наборе данных и изменяемом пороге; "
        "(б) число частых наборов разной длины при изменяемом пороге. Дать пояснения к результатам."),
      P("2. Исходные материалы", H1),
      P(f"Исходный код и данные: <link href='{REPO}' color='blue'>{REPO}</link> "
        "(файлы: apriori.py — алгоритм, experiments.py — эксперименты, apriori_lab.ipynb — ноутбук Google Colab, "
        "data/baskets.csv — данные, results/ — результаты и рисунки)."),
      P("3. Данные и реализация", H1),
      P("Файл baskets.csv: 7501 корзина, 115 различных товаров, кодировка cp1251, заголовка нет, одна строка — одна корзина. "
        "В 39 корзинах товар повторяется; поскольку поддержка считается по числу корзин, корзина трактуется как множество и дубликаты убираются. "
        "Поддержка набора — доля корзин, содержащих все его товары; порог 5% означает не менее 376 корзин из 7501."),
      P("Алгоритм (apriori.py). Свойство антимонотонности: если набор частый, то частые и все его подмножества. "
        "Поэтому уровни строятся по возрастанию длины k: (1) находятся частые 1-наборы; (2) шаг join — склеиваются пары частых "
        "(k-1)-наборов с общим префиксом длины k-2; (3) шаг prune — кандидат отбрасывается, если хотя бы одно его (k-1)-подмножество не частое; "
        "(4) подсчитывается поддержка оставшихся кандидатов; процесс идёт, пока находятся частые наборы. "
        "Подсчёт поддержки сделан в вертикальном представлении: для каждого товара хранится битовая маска корзин, в которых он встречается, "
        "а поддержка кандидата — число единиц в побитовом «И» масок (модификация в духе Apriori-TID). Это ускоряет подсчёт без изменения результата."),
      P("Подпрограммы: load_transactions(path, encoding) — чтение корзин; apriori(transactions, min_support) — поиск частых наборов; "
        "sort_itemsets(result, order) — упорядочивание («support» или «lex»); count_by_length(result) — число наборов по длинам; "
        "run_experiments(transactions, thresholds, repeats) — серия запусков с замером времени. "
        "У каждой подпрограммы в коде описаны входы и выходы."),
      P("Проверка корректности: результат сравнён с полным перебором всех наборов длины до 3 на порогах 5% и 1% — множества наборов и поддержки совпали "
        "(28 и 261 набор соответственно). Код запускается без ошибок и предупреждений (проверено с флагом -W error).")]

s += [PageBreak(), P("4. Результаты экспериментов", H1),
      P("Время — медиана 21 запуска функции apriori на одном и том же наборе данных."),
      table([["Порог, %", "Время, мс", "Всего наборов", "Длина 1", "Длина 2", "Длина 3"]] + summ[1:], [2.2*cm, 2.6*cm, 3.2*cm, 2.4*cm, 2.4*cm, 2.4*cm]),
      Spacer(1, 8), Image("results/fig_time.png", width=13*cm, height=7.4*cm),
      P("Рис. 1. Время работы при изменении порога поддержки.", C),
      Image("results/fig_lengths.png", width=13*cm, height=7.4*cm),
      P("Рис. 2. Число частых наборов длины 1, 2 и 3 при разных порогах.", C)]

top = read("results/itemsets_5pct.csv")[1:]
pairs = [r for r in top if r[1] != "1"]
